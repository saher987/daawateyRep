# Places the voice lines at their cue times (cues.json), ducks the music under
# speech, and writes:
#   ../audio.wav  - final soundtrack used by render.js
#   mouth.js      - per-frame mouth openness for Mom and Dad (lip-sync in scene3d.js)
import json, os, numpy as np, soundfile as sf
from scipy.signal import resample_poly
HERE = os.path.dirname(os.path.abspath(__file__)); SR = 48000; FPS = 30
cfg = json.load(open(f'{HERE}/cues.json')); N = int(cfg['duration'] * SR)
who = {l['id']: l['who'] for l in json.load(open(f'{HERE}/lines.json'))}
voice = np.zeros(N); mouth = {'dad': np.zeros(int(cfg['duration'] * FPS) + 1), 'mom': None}
mouth['mom'] = np.zeros_like(mouth['dad'])
for cid, at in cfg['cues']:
    x, sr = sf.read(f'{HERE}/{cid}.wav'); a = int(at * SR)
    x = x[:N - a]; voice[a:a + len(x)] += x * .95
    if who[cid] in mouth:  # RMS per video frame -> 0..1 jaw opening
        hop = SR // FPS
        for f in range(len(x) // hop):
            r = np.sqrt(np.mean(x[f * hop:(f + 1) * hop] ** 2))
            mouth[who[cid]][int(at * FPS) + f] = r
for k in mouth:
    m = mouth[k]; m /= (np.percentile(m[m > 0], 90) if (m > 0).any() else 1)
    mouth[k] = np.clip((m - .08) * 1.15, 0, 1)
music, msr = sf.read(f'{HERE}/../music.wav')
music = resample_poly(music, SR, msr) if msr != SR else music
music = np.pad(music, ((0, max(0, N - len(music))), (0, 0)))[:N]
# ducking: follow the voice envelope (attack 50 ms, release 400 ms)
env = np.abs(voice); duck = np.zeros(N); g = 0
step = 240
for i in range(0, N, step):
    v = env[i:i + step].max(); g = max(v > .02, g * np.exp(-step / SR / .4))
    duck[i:i + step] = g
duck = np.convolve(duck, np.ones(2400) / 2400, 'same')
gain = 1 - .62 * duck
mix = music * gain[:, None] * .9 + voice[:, None]
mix *= .95 / np.abs(mix).max()
sf.write(f'{HERE}/../audio.wav', mix.astype(np.float32), SR)
with open(f'{HERE}/mouth.js', 'w') as f:
    f.write('// generated by mix.py: mouth openness per frame at 30 fps\nwindow.MOUTH = ' + json.dumps(
        {'fps': FPS, **{k: [round(float(v), 2) for v in mouth[k]] for k in mouth}}) + ';\n')
print('audio.wav + mouth.js written,', cfg['duration'], 's')
